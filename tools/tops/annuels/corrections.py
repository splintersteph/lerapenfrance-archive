# corrections communes à tous les classements
GLOBAL = [
 (re.compile(r"</em>\s*«"), "</em> »"),
]


def apply(d):
    misses = []
    for m in d:
        rules = C.get(m["key"], [])
        used = [False] * len(rules)

        def fix(p):
            for i, (a, b) in enumerate(rules):
                if a in p:
                    p = p.replace(a, b)
                    used[i] = True
            for rx, b in GLOBAL:
                p = rx.sub(b, p)
            return p
        m["intro"] = [fix(p) for p in m["intro"]]
        for x in m["items"]:
            x["paras"] = [fix(p) for p in x["paras"]]
            # signatures 2021 : prénom seul en tête de notice → signature en fin
            if x["paras"] and re.fullmatch(r"[A-ZÉ][a-zéèï]+", x["paras"][0].strip()):
                x["paras"] = x["paras"][1:] + [f"<em>{x['paras'][0].strip()}</em>"]
        misses += [(m["key"], a) for (a, _), u in zip(rules, used) if not u]
    return misses


